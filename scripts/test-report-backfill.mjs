import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const db=new PGlite(),tenant='11111111-1111-4111-8111-111111111111',foreign='22222222-2222-4222-8222-222222222222';
await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
create table tenants(id uuid primary key);insert into tenants values('${tenant}'),('${foreign}');
create table brands_v2(id uuid,tenant_id uuid,slug text,is_umbrella boolean,parent_brand_id uuid);
create table creator_performance(tenant_id uuid,brand text,period_type text,report_date date);
create table client_reports(tenant_id uuid,brand_slug text,report_type text,period_start date,period_end date,revoked_at timestamptz);
insert into brands_v2 values('${tenant}','${tenant}','brand',false,null),('${foreign}','${foreign}','brand',false,null);
insert into creator_performance select '${tenant}','brand','daily',d from generate_series('2026-01-01'::date,'2026-01-31'::date,'1 day') d;
insert into creator_performance values('${foreign}','brand','daily','2025-01-01');
insert into client_reports values('${tenant}','brand','weekly','2026-01-05','2026-01-11',null);
`);
await db.exec(readFileSync('supabase/migrations/20261005224415_client_report_backfill_drafts.sql','utf8'));
const call=()=>db.query(`select prepare_report_backfill('${tenant}',array['brand']) as added`);
assert.equal((await call()).rows[0].added,5);
assert.equal((await call()).rows[0].added,0,'Repeated preparation is idempotent');
const {rows}=await db.query('select * from client_report_backfill_drafts');
assert.ok(rows.every(r=>r.tenant_id===tenant && r.status==='pending' && r.snapshot===null));
assert.equal(rows.find(r=>r.report_type==='monthly').recorded_days,31);
assert.ok(rows.filter(r=>r.report_type==='weekly').every(r=>new Date(r.period_start).getUTCDay()===1 && new Date(r.period_end).getUTCDay()===0));
assert.ok(!rows.some(r=>r.period_start==='2026-01-05'));
assert.ok(rows.some(r=>r.recorded_days<r.expected_days),'Partial weeks must remain visibly incomplete');
assert.equal((await db.query("select has_table_privilege('anon','client_report_backfill_drafts','select') as allowed")).rows[0].allowed,false);
assert.equal((await db.query("select has_table_privilege('authenticated','client_report_backfill_drafts','select') as allowed")).rows[0].allowed,false);
assert.equal((await db.query("select has_function_privilege('authenticated','prepare_report_backfill(uuid,text[])','execute') as allowed")).rows[0].allowed,false);
assert.equal((await db.query('select count(*)::int as n from client_reports')).rows[0].n,1);
await db.close();console.log('PASS historical drafts: Monday-Sunday, partial coverage, tenant isolation, existing reports preserved, idempotence and private storage');
