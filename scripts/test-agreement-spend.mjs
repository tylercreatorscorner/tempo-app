import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
const exports={};
runInNewContext(ts.transpileModule(readFileSync('src/lib/data/delivered-spend.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports});
const legacy={isAffiliate:false,retainer:1000,quota:20,postsPublished:16};
const month={kind:'month',daysInMonth:31};
assert.equal(exports.creatorEarnedShare(legacy),800);
assert.equal(exports.estimateDeliveredSpend([legacy],month).earned,800);
const recorded={...legacy,agreement:{reportPeriodComparable:true}};
assert.equal(exports.creatorEarnedShare(recorded),800);
const split={...legacy,agreement:{reportPeriodComparable:false}};
assert.equal(exports.creatorEarnedShare(split),null);
assert.equal(exports.estimateDeliveredSpend([legacy,split],month),null,'Do not show a partial portfolio estimate as its total');
const unverified={...legacy,agreement:{}};
assert.equal(exports.creatorEarnedShare(unverified),null,'Unknown recorded payment basis is not inferred');
assert.equal(exports.estimateDeliveredSpend([{...recorded,quota:30}],month).defaultQuotaShare,0,'Verified 30-post agreement is not treated as an unverified default');
console.log('PASS agreement spend: legacy parity, matched period, split-period suppression, no partial portfolio totals and verified quota basis');
